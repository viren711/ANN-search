"""Collect every report deliverable into results/REPORT_TABLES.md (+ CSVs).

Reads whatever exists (missing parts are skipped):
  results/system/system.json, results/dataset_summary.csv, dataset/processed/*/meta.json,
  results/<ds>/faiss.csv, indices/vamana/*/build_stats.json, results/*/scaling.json,
  results/sift100k/sanity_query.json, results/sift100k/param_study.csv,
  results/<ds>/compare_table.csv, indices/disk/*/meta.json, results/extra_credit/*.csv
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import pandas as pd

from ann.data import INDICES, RESULTS, load_meta

MAIN = ["sift1m", "quora", "nq"]
md = ["# Report tables (auto-generated by scripts/make_report_tables.py)\n"]


def table(df, cols=None, floatfmt=4):
    if cols:
        df = df[[c for c in cols if c in df.columns]]
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].round(floatfmt)
    try:
        return df.to_markdown(index=False)
    except ImportError:
        return "```\n" + df.to_string(index=False) + "\n```"


def section(title):
    md.append(f"\n## {title}\n")


# ---------------------------------------------------------------- system
p = RESULTS / "system" / "system.json"
if p.exists():
    s = json.loads(p.read_text())
    section("System")
    md.append("\n".join(f"- **{k}**: {v}" for k, v in s.items() if k != "env"))

# ---------------------------------------------------------------- datasets
p = RESULTS / "dataset_summary.csv"
if p.exists():
    section("Dataset summary")
    md.append(table(pd.read_csv(p)))
    m = load_meta("sift1m").get("faiss_vs_supplied_gt")
    if m:
        md.append(f"\nSIFT1M FAISS exact vs supplied ground truth: {m}")

# ---------------------------------------------------------------- part 1
section("Part 1 — FAISS exact + HNSW")
cols1 = ["method", "param", "1-recall@1", "10-recall@10", "mean_latency_ms", "qps", "build_time_s", "index_bytes",
         "latency_ms_single_query_mode", "timing_rel_spread"]
for ds in ["sift100k"] + MAIN:
    p = RESULTS / ds / "faiss.csv"
    if p.exists():
        md.append(f"\n### {ds}\n")
        md.append(table(pd.read_csv(p), cols1))
        md.append(f"\n![{ds} HNSW]({ds}/hnsw_recall_latency.png)")

# ---------------------------------------------------------------- part 2
section("Part 2 — Vamana builds")
rows = []
for f in sorted(INDICES.glob("vamana/*/build_stats.json")):
    st = json.loads(f.read_text())
    st["index"] = f.parent.name
    rows.append(st)
if rows:
    b = pd.DataFrame(rows)
    b.to_csv(RESULTS / "vamana_builds.csv", index=False)
    md.append(table(b, ["index", "N", "R", "L_build", "alpha", "build_threads", "build_time_s", "avg_out_degree",
                        "max_out_degree", "serialized_graph_bytes", "index_bytes_with_vectors",
                        "peak_build_rss_mib"]))
for f in sorted(RESULTS.glob("*/scaling.json")):
    s = json.loads(f.read_text())
    md.append(f"\n### Build-time scaling: {s['dataset']} (exponent {s['fit_exponent']:.2f}, "
              f"extrapolated full build {s['estimated_full_build_s']:.0f} s)\n")
    md.append(table(pd.DataFrame(s["measurements"])))
p = RESULTS / "sift100k" / "sanity_query.json"
if p.exists():
    md.append("\n### SIFT100K single-query sanity check\n```json\n" + p.read_text() + "\n```")

# ---------------------------------------------------------------- part 3a
p = RESULTS / "sift100k" / "param_study.csv"
if p.exists():
    section("Part 3a — SIFT100K parameter study")
    md.append(table(pd.read_csv(p), ["R", "alpha", "L_build", "L_search", "1-recall@1", "10-recall@10",
                                     "mean_latency_ms", "qps", "dist_evals_per_query", "expanded_per_query",
                                     "avg_out_degree"]))
    md.append("\n![](sift100k/param_recall_vs_Lsearch.png) ![](sift100k/param_recall_vs_latency.png)")

# ---------------------------------------------------------------- part 3b
section("Part 3b — full-dataset comparison")
for ds in MAIN:
    p = RESULTS / ds / "compare_table.csv"
    if p.exists():
        md.append(f"\n### {ds}\n")
        md.append(table(pd.read_csv(p)))
        md.append(f"\n![{ds}]({ds}/compare_recall_latency.png)")
    c = RESULTS / ds / "hnsw_counts.csv"
    if c.exists():
        md.append(f"\nHNSW work counters (full query set, 1 thread):\n")
        md.append(table(pd.read_csv(c)))
    for v in sorted((RESULTS / ds).glob("vamana_R*.csv")) if (RESULTS / ds).exists() else []:
        md.append(f"\nAll Vamana operating points ({v.name}):\n")
        md.append(table(pd.read_csv(v), ["L_search", "1-recall@1", "10-recall@10", "mean_latency_ms", "qps",
                                         "dist_evals_per_query", "expanded_per_query"]))

# ---------------------------------------------------------------- extra credit
metas = sorted(INDICES.glob("disk/*/meta.json"))
ecs = sorted((RESULTS / "extra_credit").glob("*.csv")) if (RESULTS / "extra_credit").exists() else []
if metas or ecs:
    section("Extra credit — disk-resident search")
    for f in metas:
        md.append(f"\n### Disk index {f.parent.name}\n```json\n{f.read_text()}\n```")
    (RESULTS / "extra_credit").mkdir(exist_ok=True)
    (RESULTS / "extra_credit" / "disk_index_meta.json").write_text(
        json.dumps({f.parent.name: json.loads(f.read_text()) for f in metas}, indent=2))
    for v in sorted((RESULTS / "msmarco").glob("vamana_R*.csv")) if (RESULTS / "msmarco").exists() else []:
        md.append(f"\n### MS MARCO in-memory Vamana reference (same graph, full-precision, {v.name})\n")
        md.append(table(pd.read_csv(v), ["L_search", "1-recall@1", "10-recall@10", "mean_latency_ms", "qps",
                                         "dist_evals_per_query", "expanded_per_query"]))
    for f in ecs:
        md.append(f"\n### {f.stem}\n")
        md.append(table(pd.read_csv(f), ["device", "cache", "L_search", "1-recall@1", "10-recall@10",
                                         "mean_latency_ms", "p50_latency_ms", "p95_latency_ms", "qps",
                                         "reads_per_query", "bytes_per_query", "rounds_per_query",
                                         "expansions_per_query", "storage_read_bytes_per_query", "peak_rss_mib",
                                         "resident_frac_before_run"]))

(RESULTS / "REPORT_TABLES.md").write_text("\n".join(md) + "\n")
print(f"wrote {RESULTS / 'REPORT_TABLES.md'}")
